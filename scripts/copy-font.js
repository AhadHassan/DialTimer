// Embeds the Outfit font (SIL OFL) from @fontsource/outfit into renderer/fonts.css as data URLs.
// Embedding (instead of loading files) keeps the font working even when the app sits in a folder
// whose full path exceeds Windows' 260-character limit.
const fs = require('fs');
const path = require('path');

const WEIGHTS = [200, 300]; // ExtraLight, Light
const src = path.join(__dirname, '..', 'node_modules', '@fontsource', 'outfit');
const renderer = path.join(__dirname, '..', 'renderer');

let css = '/* Generated by scripts/copy-font.js: Outfit (SIL OFL), embedded. */\n';
for (const weight of WEIGHTS) {
  const data = fs.readFileSync(path.join(src, 'files', `outfit-latin-${weight}-normal.woff2`)).toString('base64');
  css += `@font-face {\n  font-family: 'Outfit';\n  font-weight: ${weight};\n  src: url(data:font/woff2;base64,${data}) format('woff2');\n}\n`;
}
fs.writeFileSync(path.join(renderer, 'fonts.css'), css);

fs.mkdirSync(path.join(renderer, 'fonts'), { recursive: true });
if (fs.existsSync(path.join(src, 'LICENSE'))) {
  fs.copyFileSync(path.join(src, 'LICENSE'), path.join(renderer, 'fonts', 'OFL-LICENSE.txt'));
}
console.log(`Outfit ${WEIGHTS.join(' + ')} embedded in renderer/fonts.css`);
