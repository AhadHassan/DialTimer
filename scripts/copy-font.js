// Embeds the Outfit Light font (OFL) from @fontsource/outfit into renderer/fonts.css as a data URL.
// Embedding (instead of loading a file) keeps the font working even when the app sits in a folder
// whose full path exceeds Windows' 260-character limit.
const fs = require('fs');
const path = require('path');

const src = path.join(__dirname, '..', 'node_modules', '@fontsource', 'outfit');
const renderer = path.join(__dirname, '..', 'renderer');
const fontFile = path.join(src, 'files', 'outfit-latin-300-normal.woff2');

const data = fs.readFileSync(fontFile).toString('base64');
fs.writeFileSync(
  path.join(renderer, 'fonts.css'),
  `/* Generated by scripts/copy-font.js: Outfit Light (SIL OFL), embedded. */\n` +
    `@font-face {\n  font-family: 'Outfit';\n  font-weight: 300;\n  src: url(data:font/woff2;base64,${data}) format('woff2');\n}\n`
);

fs.mkdirSync(path.join(renderer, 'fonts'), { recursive: true });
if (fs.existsSync(path.join(src, 'LICENSE'))) {
  fs.copyFileSync(path.join(src, 'LICENSE'), path.join(renderer, 'fonts', 'OFL-LICENSE.txt'));
}
console.log('Outfit font embedded in renderer/fonts.css');
